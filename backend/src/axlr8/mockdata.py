class Tables:
    """Rows per table with ids assigned here, written out as COPY blocks."""

    def __init__(self):
        self.rows: dict[str, list[dict]] = defaultdict(list)
        self.ids: dict[str, int] = defaultdict(int)

    def add(self, table: str, id_col: str | None = None, **row) -> int:
        if id_col:
            self.ids[table] += 1
            row = {id_col: self.ids[table], **row}
        self.rows[table].append(row)
        return row[id_col] if id_col else 0

    def sql(self, order: list[str], sequences: dict[str, str]) -> str:
        out = ["-- Generated by backend/scripts/mock_db.py. Load after db/schema.sql.", "set search_path = axl, public;", "begin;"]
        for table in order:
            rows = self.rows.get(table)
            if not rows:
                continue
            cols = list(rows[0])
            out.append(f"copy {table} ({', '.join(cols)}) from stdin;")
            out += ["\t".join(_cell(r.get(c)) for c in cols) for r in rows]
            out.append("\\.")
        for table, col in sequences.items():
            out.append(f"select setval(pg_get_serial_sequence('{table}', '{col}'), coalesce((select max({col}) from {table}), 1));")
        out.append("commit;")
        return "\n".join(out) + "\n"


def _cell(v) -> str:
    if v is None:
        return "\\N"
    if isinstance(v, bool):
        return "t" if v else "f"
    if isinstance(v, datetime):
        return v.isoformat()
    if isinstance(v, (dict, list)):
        v = json.dumps(v)
    if isinstance(v, float):
        return f"{v:.4f}".rstrip("0").rstrip(".")
    return str(v).replace("\\", "\\\\").replace("\t", "\\t").replace("\n", "\\n")


def at(t: float) -> datetime:
    return DAY_START + timedelta(seconds=t)


def laid_out(wf: Workflow, phase: int) -> Workflow:
    """Stations 0.6 m apart, alternating sides, so the rail model can run without the app's layout."""
    keys = []
    for d in wf.devices:
        units = d.units_in_phase(phase)
        keys += [d.id] if units is None else [f"{d.id}:{u}" for u in units]
    places = [Placement(station=k, x=0.6 + 0.6 * (i // 2), side=1 if i % 2 == 0 else -1) for i, k in enumerate(keys)]
    return wf.model_copy(update={"layout": Layout(placements=places)})


def build(wf: Workflow, run: RunSettings) -> str:
    """SQL (COPY blocks) that fills db/schema.sql with one simulated day of `wf` under `run`."""
    rng = random.Random(run.seed if run.seed is not None else 1)
    phase = run.phase
    if wf.layout is None or not wf.layout.placements:
        wf = laid_out(wf, phase)
    events, rail = simulate_with_rail(wf, run)
    db = Tables()
    im = wf.imaging

    # ---------- lab
    unit_of: dict[tuple[str, int | None], int] = {}
    places = {p.station: p for p in wf.layout.placements}
    for d in wf.devices:
        kind, vendor, model, api, replacement = CATALOGUE.get(d.id, (d.name, None, d.name, None, None))
        db.add("device", device_id=d.id, name=d.name, kind="process" if d.kind == "process" else d.kind,
               vendor=vendor, model=model, api=api, replacement=replacement, notes=d.note or None)
        units = d.units_in_phase(phase)
        for u in units if units is not None else [None]:
            p = places.get(d.id if u is None else f"{d.id}:{u}")
            cap = d.capacity[u - 1] if d.capacity and u and u <= len(d.capacity) else None
            uid = db.add("device_unit", "unit_id", device_id=d.id, unit_no=u or 1, serial_no=f"{d.id.upper()}-{u or 1:03d}",
                         phase=d.unit_phases[u - 1] if u else None, capacity=cap, has_imager=bool(u and u in d.imager_units),
                         rail_x_m=p.x if p else None, rail_side=p.side if p else None)
            unit_of[(d.id, u)] = uid
    arms = len(rail.homes) if rail else 0
    for a in range(arms):
        db.add("cobot_arm", "arm_id", arm_no=a, serial_no=f"PF400-{a + 1:03d}", home_x_m=round(rail.homes[a], 3))

    # ---------- samples
    project = db.add("project", "project_id", code="AXL-DEMO", name="AXL demonstration", target="Example kinase domain")
    protein = db.add("protein_sample", "sample_id", project_id=project, name="KD-1 kinase domain", construct="KD1-His6 (res 21-310)",
                     batch="B2026-117", concentration_mg_ml=12.5, buffer="20 mM HEPES pH 7.5, 150 mM NaCl, 1 mM TCEP",
                     molecular_weight_kda=33.6, tube_barcode="PRT0001171", received_at=at(-86400), stored_at_c=-80)
    screen = db.add("screen", "screen_id", name="JCSG-plus", vendor="Molecular Dimensions", format=96)
    conditions = {}
    precipitants = ["PEG 3350", "PEG 8000", "PEG 400", "MPD", "Ammonium sulfate", "PEG 6000", "Sodium malonate", "PEG 2000 MME"]
    buffers = [("Sodium acetate", 4.6), ("Sodium citrate", 5.5), ("MES", 6.0), ("Bis-Tris", 6.5), ("HEPES", 7.5), ("Tris", 8.5), ("Bicine", 9.0)]
    for r in ROWS:
        for c in range(1, 13):
            b, ph = rng.choice(buffers)
            pr = rng.choice(precipitants)
            conditions[f"{r}{c}"] = db.add(
                "screen_condition", "condition_id", screen_id=screen, well=f"{r}{c}", buffer=f"0.1 M {b}", ph=ph,
                salt=rng.choice([None, "0.2 M NaCl", "0.2 M MgCl2", "0.2 M Li2SO4", "0.1 M CaCl2"]), precipitant=pr,
                precipitant_pct=round(rng.uniform(1.0, 2.4), 2) if pr in ("Ammonium sulfate", "Sodium malonate") else rng.choice([10, 15, 20, 25, 30]),
                additive=None)
    compounds = [db.add("compound", "compound_id", library="DSi-Poised", code=f"DSIP-{i:04d}", smiles=None,
                        mw_da=round(rng.uniform(150, 300), 2), stock_mm=500, solvent="DMSO") for i in range(1, 385)]
    for code, name, vendor, wells, dpw, vol in [
        ("MRC3-96", "MRC 3-drop 96-well sitting drop", "SWISSCI", 96, 3, 40),
        ("SBS-96-deep", "96 deep-well block", "Greiner", 96, None, 1000),
        ("Echo-384-LDV", "Echo 384 low dead volume", "Beckman Coulter", 384, None, 14),
        ("SBS-tube-1.4", "1.4 mL screw-cap tube", "Azenta", 1, None, 1400),
        ("Unipuck", "Unipuck (16 pins)", "MiTeGen", 16, None, None),
    ]:
        db.add("labware_type", labware_code=code, name=name, vendor=vendor, wells=wells, drops_per_well=dpw, working_volume_ul=vol)

    # ---------- plates (one per simulated item)
    by_item: dict[int, list] = defaultdict(list)
    for e in events:
        by_item[e.item].append(e)
    plate_of: dict[int, int] = {}
    wells_of: dict[int, dict[str, int]] = {}
    drops_of: dict[int, list[tuple[int, int, str]]] = {}  # plate -> [(drop_id, position, well)]
    crystals_of: dict[int, list[int]] = defaultdict(list)  # plate -> crystal ids
    setup_at: dict[int, datetime] = {}
    compound_plates: list[int] = []
    pucks: dict[int, int] = {}
    dewar = db.add("dewar", "dewar_id", barcode="DWR-01", location="Puck storage")
    counters = defaultdict(int)

    def new_plate(item: int, route: str, t0: float) -> int:
        role = ROLE.get(route, "reagent")
        counters[role] += 1
        prefix = {"crystal": "XP", "source": "SP", "compound": "CP", "reagent": "RG", "seed": "ST"}[role]
        older = route.startswith("soak")  # grown plates set up days before the soak
        created = at(t0) - timedelta(days=rng.randint(5, 14)) if older else at(t0)
        pid = db.add("plate", "plate_id", barcode=f"{prefix}{counters[role]:06d}", labware_code=LABWARE[role], role=role,
                     project_id=project, screen_id=screen if role in ("crystal", "source") else None, parent_plate_id=None,
                     created_at=created, set_up_at=created + timedelta(minutes=20) if older else None, discarded_at=None,
                     location_unit_id=None, location_slot=None)
        if role in ("crystal", "source", "compound"):
            wells_of[pid] = {}
            n_rows, n_cols = (16, 24) if role == "compound" else (8, 12)
            for ri in range(n_rows):
                for c in range(1, n_cols + 1):
                    name = f"{'ABCDEFGHIJKLMNOP'[ri]}{c}"
                    cid = compounds[(len(compound_plates) * 192 + ri * n_cols + c - 1) % len(compounds)] if role == "compound" else None
                    wells_of[pid][name] = db.add(
                        "well", "well_id", plate_id=pid, name=name, row_letter=name[0], col_no=c,
                        condition_id=conditions.get(name) if role != "compound" else None,
                        reservoir_ul=40 if role == "crystal" else (800 if role == "source" else None),
                        compound_id=cid, compound_volume_nl=12000 if cid else None)
        if role == "compound":
            compound_plates.append(pid)
        if older:
            make_drops(pid, created + timedelta(minutes=20), None, grown=True)
        return pid

    def make_drops(pid: int, t: datetime, op: int | None, grown: bool = False):
        drops = []
        ratios = {1: (100, 100), 2: (100, 200), 3: (200, 100)}  # protein : well solution per sub-well
        for name, wid in wells_of[pid].items():
            for pos in (1, 2, 3):
                p_nl, r_nl = ratios[pos]
                did = db.add("droplet", "drop_id", well_id=wid, position=pos, sample_id=protein, protein_nl=p_nl,
                             reservoir_nl=r_nl, seed_nl=0, additive_nl=0, set_up_at=t, set_up_op_id=op)
                drops.append((did, pos, name))
        drops_of[pid] = drops
        setup_at[pid] = t
        if grown:  # crystals that grew before today
            for did, _, _ in drops:
                if rng.random() < 0.18:
                    crystals_of[pid].append(db.add(
                        "crystal", "crystal_id", drop_id=did, first_image_id=None, first_seen_at=t + timedelta(hours=rng.choice([16, 32, 64])),
                        x_um=round(rng.uniform(-300, 300), 1), y_um=round(rng.uniform(-300, 300), 1),
                        length_um=round(rng.uniform(20, 180), 1), width_um=round(rng.uniform(10, 60), 1),
                        habit=rng.choice(["rod", "plate", "cube", "needle"]), uv_positive=rng.random() < 0.9))

    def operation(item, e_start, e_end, action=None, **resp) -> int:
        dev = e_start.device
        uid = unit_of[(dev, e_start.unit)]
        return db.add("operation", "op_id", unit_id=uid, plate_id=plate_of.get(item), action=action or ACTION.get(dev, dev),
                      route=e_start.route, step_no=e_start.step, queued_at=None, started_at=at(e_start.t),
                      ended_at=at(e_end.t), status="ok", error_code=None, error_message=None,
                      operator="operator-1" if dev.startswith("map_") else None, api_call_id=f"{dev}-{uuid(rng)}",
                      request={"device": dev, "unit": e_start.unit, "step": e_start.step}, response=resp or None)

    def imaging(pid: int, unit: int, purpose: str, t0: float, t1: float, op: int | None, due: float | None, modalities: list[str]):
        if pid not in drops_of:
            return
        set_up = setup_at[pid]
        hours = (at(t0) - set_up).total_seconds() / 3600
        sid = db.add("imaging_session", "session_id", op_id=op, plate_id=pid, unit_id=unit, purpose=purpose,
                     due_at=at(due) if due is not None else None, started_at=at(t0), ended_at=at(t1),
                     hours_since_setup=round(hours, 2), temp_c=round(rng.gauss(20, 0.05), 2),
                     seconds_per_well=im.seconds_per_well, modalities="{" + ",".join(modalities) + "}")
        per_drop = (t1 - t0) / max(1, len(drops_of[pid]))
        crystal_drops = defaultdict(list)
        for cid_row in db.rows["crystal"]:
            if cid_row["crystal_id"] in crystals_of[pid]:
                crystal_drops[cid_row["drop_id"]].append(cid_row)
        for k, (did, _, well) in enumerate(drops_of[pid]):
            taken = at(t0 + k * per_drop)
            for mod in modalities:
                img = db.add("drop_image", "image_id", session_id=sid, drop_id=did, modality=mod, taken_at=taken,
                             z_slices=9 if mod == "visible" else 5, z_step_um=25 if mod == "visible" else 40,
                             exposure_ms=round(rng.uniform(8, 20) if mod == "visible" else rng.uniform(200, 600), 2),
                             objective="5x", pixel_size_um=1.2, focus_score=round(rng.uniform(0.55, 0.98), 3),
                             uri=f"s3://axl-images/{pid}/{well}-{did}/{sid}-{mod}/stack.tif",
                             edf_uri=f"s3://axl-images/{pid}/{well}-{did}/{sid}-{mod}/edf.jpg",
                             drop_area_px=rng.randint(90000, 160000), drop_found=rng.random() > 0.01)
                if mod != "visible":
                    continue
                seen = [c for c in crystal_drops.get(did, []) if c["first_seen_at"] <= taken]
                outcome = "crystal" if seen else rng.choices(
                    ["clear", "precipitate", "skin", "phase_separation", "microcrystals"], [50, 30, 5, 8, 7 * min(1, hours / 48)])[0]
                db.add("drop_score", "score_id", image_id=img, drop_id=did, scored_at=taken + timedelta(seconds=40),
                       scorer="MARCO v2", outcome=outcome, confidence=round(rng.uniform(0.6, 0.99), 3), crystals_seen=len(seen))
                for c in seen:
                    if c["first_image_id"] is None:
                        c["first_image_id"] = img
                    grow = min(1.0, 0.4 + hours / 120)
                    db.add("crystal_observation", crystal_id=c["crystal_id"], image_id=img,
                           length_um=round(c["length_um"] * grow, 1), width_um=round(c["width_um"] * grow, 1))
        return sid

    def new_crystals(pid: int, start: datetime):
        """Today's crystal plates: some drops grow crystals within the imaging window."""
        for did, pos, _ in drops_of[pid]:
            if rng.random() < 0.12 + 0.04 * (pos == 3):
                crystals_of[pid].append(db.add(
                    "crystal", "crystal_id", drop_id=did, first_image_id=None,
                    first_seen_at=start + timedelta(hours=rng.choice([4, 8, 16, 16, 32])),
                    x_um=round(rng.uniform(-300, 300), 1), y_um=round(rng.uniform(-300, 300), 1),
                    length_um=round(rng.uniform(15, 120), 1), width_um=round(rng.uniform(8, 40), 1),
                    habit=rng.choice(["rod", "plate", "cube", "needle"]), uv_positive=rng.random() < 0.85))

    rail_moves = {(m.item, round(m.start, 6)): m for m in (rail.moves if rail else [])}
    source_for_mosquito: dict[str, int] = {}
    puck_pos: dict[int, int] = defaultdict(int)
    soak_plate_for_echo: dict[str, int] = {}

    def station_unit(key: str) -> int | None:
        dev, _, u = key.partition(":")
        return unit_of.get((dev, int(u) if u else None))

    for item, evs in sorted(by_item.items()):  # one puck per harvested plate, before the harvests fill them
        if evs[0].route == "pins":
            counters["puck"] += 1
            pucks[item] = db.add("puck", "puck_id", barcode=f"PK{counters['puck']:05d}", puck_type="Unipuck", dewar_id=None, dewar_position=None)

    for item, evs in sorted(by_item.items()):  # every plate exists before the steps that use another plate
        if evs[0].route != "pins":
            plate_of[item] = new_plate(item, evs[0].route, evs[0].t)

    for item, evs in sorted(by_item.items()):
        route = evs[0].route
        pid = plate_of.get(item)
        open_proc: dict[int, object] = {}
        ready_at = None
        last_unit = None
        for e in evs:
            if e.kind == "move_ready":
                ready_at = e.t
            elif e.kind == "move_start" and e.cobot and pid is not None and arms > 0:
                m = rail_moves.get((item, round(e.t, 6)))
                db.add("cobot_move", "move_id", arm_id=(m.arm + 1) if m else 1, plate_id=pid, from_unit_id=last_unit,
                       to_unit_id=station_unit(m.target) if m else None,
                       ready_at=at(ready_at) if ready_at is not None else None, started_at=at(e.t),
                       picked_at=at(m.pick) if m else None, placed_at=at(m.place) if m else None, ended_at=at(m.end) if m else None,
                       rail_from_m=round(places[m.source].x, 3) if m and m.source in places else None,
                       rail_to_m=round(places[m.target].x, 3) if m and m.target in places else None,
                       blocked_s=round(m.blocked, 2) if m else 0, gripper_force_n=round(rng.uniform(9, 11), 2),
                       gripper_width_mm=82.5 if pid else 12.0, plate_present=True, status="ok")
            elif e.kind == "process_start":
                open_proc[e.item] = e
            elif e.kind == "process_end" and e.item in open_proc:
                s = open_proc.pop(e.item)
                dev, step = s.device, wf.route(route).steps[s.step]
                last_unit = unit_of[(dev, s.unit)]
                if dev == "waste" or dev.startswith("map_") or dev == "ln2":
                    operation(item, s, e)
                    continue
                if pid is None:  # a puck of pins
                    op = operation(item, s, e)
                    if dev == "vitrification":
                        harvested = [h for h in db.rows["harvest"] if h.get("_puck") == item and h["pin_id"] is not None]
                        for h in harvested:
                            db.add("vitrification", op_id=op, pin_id=h["pin_id"], method="plunge", ln2_temp_c=round(rng.uniform(-196, -194), 2),
                                   transfer_s=round(rng.uniform(4, 9), 2), plunged_at=at(e.t))
                    elif dev == "puck_storage":
                        counters["dewar_pos"] += 1
                        db.rows["puck"][pucks[item] - 1].update(dewar_id=dewar, dewar_position=counters["dewar_pos"])
                        db.add("puck_storage_event", op_id=op, puck_id=pucks[item], direction="in", dewar_id=dewar,
                               ln2_level_pct=round(rng.uniform(70, 95), 2))
                    continue
                if dev in ("dfsa", "dc2sa", "spectroq"):
                    label = step.label or ""
                    going_in = step.store or step.image or "Return" in label or "storage" in label
                    op = operation(item, s, e, "store" if step.store else ("image" if step.image else ("store" if going_in else "retrieve")))
                    db.add("storage_event", op_id=op, direction="in" if going_in else "out",
                           cassette=rng.randint(1, 10), level=rng.randint(1, 22),
                           set_temp_c={"dfsa": -20, "dc2sa": 20, "spectroq": 20}[dev],
                           temp_c=round(rng.gauss({"dfsa": -20, "dc2sa": 20, "spectroq": 20}[dev], 0.1), 2),
                           humidity_pct=round(rng.uniform(5, 10), 2) if dev == "dc2sa" else None,
                           door_open_s=round(rng.uniform(3, 6), 2), barcode_read=db.rows["plate"][pid - 1]["barcode"], barcode_match=True)
                    if step.image:
                        purpose = "entry" if step.store else ("pre_soak" if "Pre" in (step.label or "") else "post_soak")
                        if step.store:
                            new_crystals(pid, at(e.t))
                        imaging(pid, last_unit, purpose, s.t, e.t, op, None, ["visible", "uv"] if purpose != "entry" else ["visible"])
                    if step.store:
                        db.rows["plate"][pid - 1].update(location_unit_id=last_unit, location_slot=f"C{rng.randint(1, 10)}-L{rng.randint(1, 22)}")
                    continue
                op = operation(item, s, e)
                if dev == "peeler":
                    db.add("peel_event", op_id=op, tape_adhere_s=round(rng.uniform(1.5, 2.5), 2), peel_speed="normal",
                           begin_location="A1 edge", seal_detected_before=True, seal_removed=rng.random() > 0.002,
                           tape_remaining=400 - len(db.rows["peel_event"]) % 400)
                elif dev in ("sealer", "plateloc"):
                    foil = dev == "plateloc"
                    db.add("seal_event", op_id=op, sealer="plateloc" if foil else "a4s",
                           seal_material="Peelable aluminium" if foil else "Clear optical heat seal",
                           seal_lot=f"L{2026}-{rng.randint(100, 999)}", set_temp_c=165 if foil else 150,
                           actual_temp_c=round(rng.gauss(165 if foil else 150, 1.0), 1), seal_time_s=2.0 if foil else 1.5,
                           air_pressure_kpa=round(rng.uniform(600, 620), 1) if foil else None,
                           seals_remaining=5000 - len(db.rows["seal_event"]))
                elif dev == "centrifuge":
                    db.add("centrifuge_run", op_id=op, rpm=2000, rcf_g=round(2000 ** 2 * 1.118e-5 * 12.4, 1), spin_s=round(e.t - s.t - 20, 1),
                           accel_pct=80, decel_pct=60, bucket=rng.randint(1, 2), counterweight_plate_id=None, imbalance_detected=False)
                elif dev == "benchcel":
                    db.add("plate_supply_event", op_id=op, stack=rng.randint(1, 4), plates_left_in_stack=rng.randint(0, 40),
                           labware_code=db.rows["plate"][pid - 1]["labware_code"])
                elif dev == "labeller":
                    db.add("label_event", op_id=op, barcode=db.rows["plate"][pid - 1]["barcode"], symbology="Code 128",
                           sides="south,west", verified=True, print_quality=rng.choice(["A", "A", "B"]))
                elif dev == "xl200_thaw":
                    db.add("thaw_event", op_id=op, start_temp_c=round(rng.uniform(-21, -19), 1), end_temp_c=round(rng.uniform(19, 21), 1),
                           thaw_s=round(e.t - s.t, 1), mixed=True)
                elif dev == "xl200":
                    role = db.rows["plate"][pid - 1]["role"]
                    if role in ("crystal", "source"):  # reservoir or source-block fill, one 8-channel pass per column
                        vol = 40 if role == "crystal" else 800
                        for c in range(1, 13):
                            for r in ROWS:
                                db.add("liquid_transfer", "transfer_id", op_id=op, command_id=uuid(rng), pipette="8-channel",
                                       tip_rack_slot="B2", source_barcode=f"SCR-JCSG-{r}{c}", source_well=f"{r}{c}", dest_plate_id=pid,
                                       dest_well=f"{r}{c}", volume_ul=vol, detected_volume_ul=round(vol * rng.uniform(5, 12), 3),
                                       aspirate_flow_ul_s=50, dispense_flow_ul_s=80, decapped=False, tip_reused=False, status="ok")
                    else:
                        db.add("liquid_transfer", "transfer_id", op_id=op, command_id=uuid(rng), pipette="1-channel",
                               tip_rack_slot="A1", source_barcode="PRT0001171", source_well="A1", dest_plate_id=pid, dest_well="A1",
                               volume_ul=50, detected_volume_ul=round(rng.uniform(80, 120), 3), aspirate_flow_ul_s=10,
                               dispense_flow_ul_s=10, decapped=True, tip_reused=False, status="ok")
                elif dev.startswith("mosquito"):
                    role = db.rows["plate"][pid - 1]["role"]
                    if role == "source":
                        source_for_mosquito[dev] = pid
                    elif role == "crystal":
                        db.rows["plate"][pid - 1].update(parent_plate_id=source_for_mosquito.get(dev), set_up_at=at(e.t))
                        db.add("drop_setup_run", op_id=op, source_plate_id=source_for_mosquito.get(dev), protocol="3-drop 1:1 1:2 2:1",
                               drop_type="lcp" if dev == "mosquito_lcp" else "sitting", humidity_pct=round(rng.uniform(80, 90), 2),
                               temp_c=round(rng.gauss(20, 0.3), 2), tips_used=96 * 2, aspirate_speed="normal",
                               dispense_height_mm=round(rng.uniform(0.3, 0.5), 2), lcp_bolus_nl=50 if dev == "mosquito_lcp" else None,
                               set_up_s=round(e.t - s.t, 1))
                        make_drops(pid, at(e.t), op)
                elif dev == "echo":
                    role = db.rows["plate"][pid - 1]["role"]
                    if role == "compound":
                        soak_plate_for_echo[route] = pid
                        continue
                    src = compound_plates[0] if route == "soak_1" or len(compound_plates) < 2 else compound_plates[1]
                    targets = [c for c in db.rows["crystal"] if c["crystal_id"] in crystals_of[pid]]
                    wells = list(wells_of[src])
                    for k, c in enumerate(targets):
                        sw = wells[(len(db.rows["echo_transfer"]) + k) % len(wells)]
                        db.add("echo_survey", "survey_id", op_id=op, source_plate_id=src, well=sw, volume_nl=round(rng.uniform(9000, 12000), 2),
                               dmso_pct=round(rng.uniform(94, 99.5), 2), fluid_thickness_mm=round(rng.uniform(1.8, 2.4), 3), status="ok")
                        req = rng.choice([25.0, 50.0])
                        db.add("echo_transfer", "transfer_id", op_id=op, source_plate_id=src, source_well=sw, drop_id=c["drop_id"],
                               requested_nl=req, actual_nl=round(req * rng.uniform(0.97, 1.0), 2), droplets=int(req / 2.5),
                               fluid_class="384LDV_DMSO", status="ok", skip_reason=None, soak_started_at=at(e.t), soak_s=None)
                elif dev == "xact":
                    targets = [c for c in db.rows["crystal"] if c["crystal_id"] in crystals_of[pid]][:16]
                    span = (e.t - s.t) / max(1, len(targets))
                    spawned = next((x for x in by_item if by_item[x][0].route == "pins" and by_item[x][0].t >= e.t - 1e-6
                                    and x not in counters.setdefault("_used_pucks", set())), None)
                    if spawned is not None:
                        counters["_used_pucks"].add(spawned)
                    for k, c in enumerate(targets):
                        t0, ok = s.t + k * span, rng.random() > 0.08
                        pin = None
                        if ok:
                            counters["pin"] += 1
                            puck_pos[spawned] += 1
                            pin = db.add("pin", "pin_id", barcode=f"PN{counters['pin']:06d}", loop_type="MiTeGen MicroLoop",
                                         loop_size_um=rng.choice([50, 75, 100, 150]),
                                         puck_id=pucks.get(spawned),
                                         puck_position=puck_pos[spawned] if spawned is not None else None)
                        db.add("harvest", "harvest_id", op_id=op, crystal_id=c["crystal_id"], pin_id=pin, attempt=1, started_at=at(t0),
                               ended_at=at(t0 + span), success=ok, failure_reason=None if ok else rng.choice(["crystal stuck to drop", "lost from loop"]),
                               cryo_solution="25% glycerol", cryo_s=round(rng.uniform(2, 6), 2),
                               image_before_uri=f"s3://axl-images/harvest/{c['crystal_id']}/before.jpg",
                               image_after_uri=f"s3://axl-images/harvest/{c['crystal_id']}/after.jpg", _puck=spawned)
                        for et in db.rows["echo_transfer"]:
                            if et["drop_id"] == c["drop_id"] and et["soak_s"] is None:
                                et["soak_s"] = round((at(t0) - et["soak_started_at"]).total_seconds(), 1)

    # pucks are created when their item starts; pins point at them by item
    for e in events:
        if e.kind == "image_start":
            end = next(x for x in by_item[e.item] if x.kind == "image_end" and x.t >= e.t)
            op = operation(e.item, e, end, "image", purpose="growth", due=at(e.due).isoformat() if e.due is not None else None)
            imaging(plate_of[e.item], unit_of[(e.device, e.unit)], "growth", e.t, end.t, op, e.due, ["visible"])

    # incubators and stores log their environment every 10 min
    day_end = max(e.t for e in events)
    for (dev, u), uid in unit_of.items():
        if dev in ("spectroq", "dfsa", "dc2sa"):
            base = {"spectroq": 20, "dfsa": -20, "dc2sa": 20}[dev]
            t = 0.0
            while t <= day_end:
                db.add("environment_reading", unit_id=uid, t=at(t), temp_c=round(base + 0.05 * math.sin(t / 3600) + rng.gauss(0, 0.02), 2),
                       humidity_pct=round(rng.uniform(5, 10), 2) if dev == "dc2sa" else None, vibration_mg=round(rng.uniform(0.5, 2), 2))
                t += 600

    for h in db.rows["harvest"]:
        h.pop("_puck", None)
    order = [
        "device", "device_unit", "cobot_arm", "project", "protein_sample", "screen", "screen_condition", "compound",
        "labware_type", "plate", "well", "operation", "droplet", "cobot_move", "storage_event", "environment_reading",
        "peel_event", "seal_event", "centrifuge_run", "plate_supply_event", "label_event", "liquid_transfer", "thaw_event",
        "drop_setup_run", "echo_survey", "echo_transfer", "imaging_session", "drop_image", "drop_score", "crystal",
        "crystal_observation", "dewar", "puck", "pin", "harvest", "vitrification", "puck_storage_event",
    ]
    # crystal rows reference images (first_image_id) and images reference drops: load crystals after images.
    sequences = {t: c for t, c in [
        ("device_unit", "unit_id"), ("cobot_arm", "arm_id"), ("project", "project_id"), ("protein_sample", "sample_id"),
        ("screen", "screen_id"), ("screen_condition", "condition_id"), ("compound", "compound_id"), ("plate", "plate_id"),
        ("well", "well_id"), ("operation", "op_id"), ("droplet", "drop_id"), ("cobot_move", "move_id"),
        ("liquid_transfer", "transfer_id"), ("echo_survey", "survey_id"), ("echo_transfer", "transfer_id"),
        ("imaging_session", "session_id"), ("drop_image", "image_id"), ("drop_score", "score_id"), ("crystal", "crystal_id"),
        ("dewar", "dewar_id"), ("puck", "puck_id"), ("pin", "pin_id"), ("harvest", "harvest_id"),
    ]}
    return db.sql(order, sequences)


def uuid(rng: random.Random) -> str:
    return "%08x-%04x-%04x-%04x-%012x" % (rng.getrandbits(32), rng.getrandbits(16), rng.getrandbits(16), rng.getrandbits(16), rng.getrandbits(48))
